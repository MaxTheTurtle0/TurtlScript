// Package compiler lowers checked TurtlScript programs to self-contained Go
// source. Generated programs execute native function bodies, without an AST.
package compiler

import (
	"bytes"
	"context"
	_ "embed"
	"fmt"
	"go/format"
	"go/interpreter/ast"
	"go/interpreter/checker"
	"go/interpreter/object"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
)

//go:embed rt/runtime.go
var runtimeSource string

// Generate checks the entire program before emitting a single Go source file.
// The source embeds its runtime and only imports Go standard library packages.
func Generate(program *ast.Program) ([]byte, error) {
	if program == nil {
		return nil, fmt.Errorf("cannot compile a nil program")
	}
	if _, errors := checker.NewSession().Check(program); len(errors) != 0 {
		return nil, fmt.Errorf("Type errors:\n\t%s", strings.Join(errors, "\n\t"))
	}
	g := &generator{}
	body := &bodyGenerator{generator: g, layout: newLayout(nil, nil, program.Statements)}
	body.frame("nil")
	last := body.block(program.Statements)
	body.line("return %s", last)
	source := strings.Replace(runtimeSource, "package rt", "package main", 1)
	source += "\nfunc tsProgram(output io.Writer, depth int) value {\n" + body.String() + "}\n"
	source += strings.Join(g.functions, "\n")
	source += "\nfunc main() { run(tsProgram) }\n"
	formatted, err := format.Source([]byte(source))
	if err != nil {
		return nil, fmt.Errorf("format generated Go: %w", err)
	}
	return append([]byte("// Code generated by TurtlScript. DO NOT EDIT.\n"), formatted...), nil
}

// Build invokes the Go toolchain and replaces output only after a successful
// build. The temporary module needs neither a checkout nor external modules.
func Build(ctx context.Context, program *ast.Program, output string) error {
	source, err := Generate(program)
	if err != nil {
		return err
	}
	if output == "" {
		return fmt.Errorf("output path is required")
	}
	output, err = filepath.Abs(output)
	if err != nil {
		return err
	}
	workspace, err := os.MkdirTemp("", "turtls-aot-*")
	if err != nil {
		return err
	}
	defer os.RemoveAll(workspace)
	if err := os.WriteFile(filepath.Join(workspace, "go.mod"), []byte("module turtlscript-aot\n\ngo 1.27.2\n"), 0600); err != nil {
		return err
	}
	if err := os.WriteFile(filepath.Join(workspace, "main.go"), source, 0600); err != nil {
		return err
	}
	staging, err := os.MkdirTemp(filepath.Dir(output), ".turtls-build-*")
	if err != nil {
		return err
	}
	defer os.RemoveAll(staging)
	binary := filepath.Join(staging, "program")
	cmd := exec.CommandContext(ctx, "go", "build", "-trimpath", "-o", binary, ".")
	cmd.Dir = workspace
	cmd.Env = append(os.Environ(), "GOWORK=off")
	message, err := cmd.CombinedOutput()
	if err != nil {
		return fmt.Errorf("Go build: %w\n%s", err, bytes.TrimSpace(message))
	}
	if err := os.Rename(binary, output); err != nil {
		return fmt.Errorf("write executable: %w", err)
	}
	return nil
}

type generator struct {
	functions    []string
	nextFunction int
}

type bodyGenerator struct {
	*generator
	strings.Builder
	nextValue int
	layout    *layout
}

func (g *bodyGenerator) line(format string, args ...any) {
	fmt.Fprintf(&g.Builder, format+"\n", args...)
}

func (g *bodyGenerator) temporary(expression string) string {
	name := fmt.Sprintf("v%d", g.nextValue)
	g.nextValue++
	g.line("%s := %s", name, expression)
	g.line("if control(%s) { return %s }", name, name)
	return name
}

func (g *bodyGenerator) scalar(expression string) string {
	name := fmt.Sprintf("i%d", g.nextValue)
	g.nextValue++
	g.line("%s := %s", name, expression)
	g.line("_ = %s", name)
	return name
}

func (g *bodyGenerator) frame(parent string) {
	g.line("var storage [%d]value", len(g.layout.slots))
	g.line("env := &scope{slots: storage[:], parent: %s}", parent)
	// Empty functions need no environment reads, but still share this prologue.
	g.line("_ = env")
}

func (g *bodyGenerator) block(statements []ast.Statement) string {
	last := "nullValue"
	for _, statement := range statements {
		switch node := statement.(type) {
		case *ast.ExpressionStatement:
			last = g.expression(node.Expression)
		case *ast.LetStatement:
			v := g.expression(node.Value)
			g.line("env.slots[%d] = %s", g.layout.slots[node.Name.Value], v)
			last = "nullValue"
		case *ast.ReturnStatement:
			v := g.expression(node.ReturnValue)
			g.line("return %s", v)
			return "nullValue"
		}
	}
	return last
}

func (g *bodyGenerator) expression(expression ast.Expression) string {
	switch node := expression.(type) {
	case *ast.IntegerLiteral:
		return fmt.Sprintf("value{kind: intKind, integer: int64(%d)}", node.Value)
	case *ast.StringLiteral:
		return "value{kind: stringKind, text: " + strconv.Quote(node.Value) + "}"
	case *ast.Boolean:
		return fmt.Sprintf("boolean(%t)", node.Value)
	case *ast.NullLiteral:
		return "nullValue"
	case *ast.Identifier:
		return g.identifier(node.Value)
	case *ast.PrefixExpression:
		if node.IntegerOperand {
			return "value{kind: intKind, integer: " + g.integer(node) + "}"
		}
		right := g.expression(node.Right)
		return g.temporary(fmt.Sprintf("prefix(%q, %s)", node.Operator, right))
	case *ast.InfixExpression:
		if node.IntegerOperands {
			switch node.Operator {
			case "==", "!=", "<", "<=", ">", ">=":
				left := g.integer(node.Left)
				right := g.integer(node.Right)
				return g.temporary(fmt.Sprintf("boolean(%s %s %s)", left, node.Operator, right))
			default:
				return "value{kind: intKind, integer: " + g.integer(node) + "}"
			}
		}
		left := g.expression(node.Left)
		if node.Operator == "&&" || node.Operator == "||" {
			result := g.temporary("boolean(truth(" + left + "))")
			condition := "truth(" + left + ")"
			if node.Operator == "||" {
				condition = "!" + condition
			}
			g.line("if %s {", condition)
			right := g.expression(node.Right)
			g.line("%s = boolean(truth(%s))", result, right)
			g.line("}")
			return result
		}
		right := g.expression(node.Right)
		return g.temporary(fmt.Sprintf("infix(%q, %s, %s)", node.Operator, left, right))
	case *ast.IfExpression:
		condition := g.expression(node.Condition)
		result := g.temporary("nullValue")
		g.line("if truth(%s) {", condition)
		last := g.block(node.Consequence.Statements)
		g.line("%s = %s", result, last)
		if node.Alternative != nil {
			g.line("} else {")
			last = g.block(node.Alternative.Statements)
			g.line("%s = %s", result, last)
		}
		g.line("}")
		return result
	case *ast.FunctionLiteral:
		name := fmt.Sprintf("tsFunction%d", g.nextFunction)
		g.nextFunction++
		body := &bodyGenerator{generator: g.generator, layout: newLayout(g.layout, node.Parameters, node.Body.Statements)}
		body.frame("parent")
		for i, parameter := range node.Parameters {
			body.line("env.slots[%d] = args.at(%d)", body.layout.slots[parameter.Value], i)
		}
		last := body.block(node.Body.Statements)
		body.line("return %s", last)
		g.functions = append(g.functions, "func "+name+"(parent *scope, output io.Writer, depth int, args arguments) value {\n"+body.String()+"}\n")
		printed := (&object.Function{Parameters: node.Parameters, Body: node.Body, Signature: node.Signature}).Inspect()
		g.functions = append(g.functions, fmt.Sprintf("var %sCode = functionCode{parameters: %d, display: %q, body: %s}\n", name, len(node.Parameters), printed, name))
		return g.temporary(fmt.Sprintf("value{kind: functionKind, function: &function{code: &%sCode, parent: env}}", name))
	case *ast.CallExpression:
		callee := g.expression(node.Function)
		g.temporary(fmt.Sprintf("checkCall(%s, %d, depth)", callee, len(node.Arguments)))
		args := []string{}
		for _, argument := range node.Arguments {
			args = append(args, g.expression(argument))
		}
		first, tail := args, []string{}
		if len(first) > 2 {
			first, tail = args[:2], args[2:]
		}
		packed := fmt.Sprintf("arguments{first: [2]value{%s}, count: %d", strings.Join(first, ","), len(args))
		if len(tail) != 0 {
			packed += ", tail: []value{" + strings.Join(tail, ",") + "}"
		}
		return g.temporary("call(" + callee + ", output, depth, " + packed + "})")
	default:
		panic(fmt.Sprintf("compiler: unsupported checked expression %T", expression))
	}
}
